        if temporal.get("version") == 2:
            temporal_table = (
                _table(
                    [
                        {
                            key: temporal[key]
                            for key in (
                                "window_rows",
                                "flagged_transaction_rows",
                                "unflagged_transaction_rows",
                                "window_business_date_mismatch_warning",
                            )
                        }
                    ]
                )
                + "\n\n"
                + _table(
                    [
                        {
                            "reason": reason,
                            "overlapping_findings": count,
                            "primary_reason_rows": temporal["primary_reason_counts"][reason],
                        }
                        for reason, count in temporal["findings"].items()
                    ]
                )
            )
        else:
            temporal_table = _table([temporal])
