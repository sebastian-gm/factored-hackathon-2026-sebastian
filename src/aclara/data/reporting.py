        _table([profile["candidate_counts"]]),
        "",
        _table([profile["pending_window"]]),
        "",
        "The brief's reference figures (494,755 transactions; candidate median 3, p90 8, maximum 28; 26,475 customers without candidates; 9,963 pending and 8,741 older than 14 days) are not forced to match. This report uses exact timestamp windows and all customers, including zeros. Pipeline values above are authoritative.",
        "",
